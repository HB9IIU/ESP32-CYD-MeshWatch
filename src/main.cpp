void handleRoot() {
  webServer.send(200, "text/html", captivePortalPage());
}

void handleConnect() {
  String ssid = webServer.arg("ssid");
  String password = webServer.arg("password");

  if (ssid.isEmpty()) {
    webServer.send(400, "text/plain", "Missing SSID");
    return;
  }

  if (saveWifiCredentials(ssid, password)) {
    webServer.send(200, "text/html", "<html><body><h1>Saved</h1><p>Connecting to WiFi...</p></body></html>");
    delay(1000);
    ESP.restart();
  } else {
    webServer.send(500, "text/plain", "Failed to save WiFi settings");
  }
}

void handleNotFound() {
  webServer.sendHeader("Location", "/", true);
  webServer.send(302, "text/plain", "");
}

