// "14:32" for today, "Tue 14:32" for older messages.
void formatMessageTime(time_t timestamp, char *destination, size_t destinationSize) {
  const time_t now = time(nullptr);
  if (timestamp < kValidEpoch || now < kValidEpoch) {
    formatClock(timestamp, destination, destinationSize);
    return;
  }
  struct tm messageTime {};
  struct tm today {};
  localtime_r(&timestamp, &messageTime);
  localtime_r(&now, &today);
  const bool sameDay = messageTime.tm_yday == today.tm_yday && messageTime.tm_year == today.tm_year;
  strftime(destination, destinationSize, sameDay ? "%H:%M" : "%a %H:%M", &messageTime);
}

void displayMessage(const StoredMessage &message, bool unread) {
  char clock[16];
  formatMessageTime(static_cast<time_t>(message.timestamp), clock, sizeof(clock));
  char meta[40];
  snprintf(meta, sizeof(meta), "%s  %s", message.channel, clock);
  addMessageCard(message.sender, meta, message.text, unread);
  onScreensaverMessage(unread);
}

uint32_t storedMessageCrc(const StoredMessage &message) {
  return esp_rom_crc32_le(0, reinterpret_cast<const uint8_t *>(&message), offsetof(StoredMessage, crc));
}

bool isValidStoredMessage(const StoredMessage &message) {
  return message.magic == kStoredMessageMagic && message.sequence != 0 && message.crc == storedMessageCrc(message);
}

bool isRecentPacket(uint32_t packetId) {
  if (packetId == 0) {
    return false;
  }
  for (uint8_t index = 0; index < kRecentPacketIds; ++index) {
    if (recentPacketIds[index] == packetId) {
      return true;
    }
  }
  return false;
}

void rememberPacketId(uint32_t packetId) {
  if (packetId == 0) {
    return;
  }
  recentPacketIds[recentPacketIdIndex] = packetId;
  recentPacketIdIndex = (recentPacketIdIndex + 1) % kRecentPacketIds;
}

// Mounts the data partition and makes sure the ring file exists at full size.
void initMessageStore() {
  if (!LittleFS.begin(true)) {
    Serial.println("Message store: LittleFS mount failed, history disabled");
    return;
  }

  constexpr size_t kStoreSize = sizeof(StoredMessage) * kStoredMessageSlots;
  if (!LittleFS.exists(kMessageStorePath) || LittleFS.open(kMessageStorePath, "r").size() != kStoreSize) {
    File file = LittleFS.open(kMessageStorePath, "w");
    if (!file) {
      Serial.println("Message store: cannot create file, history disabled");
      return;
    }
    const StoredMessage empty{};
    for (uint16_t slot = 0; slot < kStoredMessageSlots; ++slot) {
      file.write(reinterpret_cast<const uint8_t *>(&empty), sizeof(empty));
    }
    file.close();
    Serial.println("Message store: created empty history");
  }
  messageStoreReady = true;
}

void storeMessage(StoredMessage &message) {
  if (!messageStoreReady) {
    return;
  }
  message.magic = kStoredMessageMagic;
  message.sequence = nextStoreSequence++;
  message.crc = storedMessageCrc(message);

  File file = LittleFS.open(kMessageStorePath, "r+");
  if (!file || !file.seek(static_cast<uint32_t>(nextStoreSlot) * sizeof(StoredMessage)) ||
      file.write(reinterpret_cast<const uint8_t *>(&message), sizeof(message)) != sizeof(message)) {
    Serial.println("Message store: write failed");
  }
  file.close();
  nextStoreSlot = (nextStoreSlot + 1) % kStoredMessageSlots;
  if (storedMessageCount < kStoredMessageSlots) {
    ++storedMessageCount;
  }
}

// Finds the write position and shows the newest stored messages: those from the last
// 24 hours when the time is known, otherwise simply the newest ones.
void restoreMessages() {
  if (!messageStoreReady) {
    return;
  }
  File file = LittleFS.open(kMessageStorePath, "r");
  if (!file) {
    return;
  }

  const time_t now = time(nullptr);
  const bool timeKnown = now >= kValidEpoch;
  uint32_t newestSequence = 0;
  uint32_t sequences[kMaxMessages];
  uint16_t slots[kMaxMessages];
  uint8_t count = 0;
  StoredMessage message{};

  for (uint16_t slot = 0; slot < kStoredMessageSlots; ++slot) {
    if (file.read(reinterpret_cast<uint8_t *>(&message), sizeof(message)) != sizeof(message)) {
      break;
    }
    if (!isValidStoredMessage(message)) {
      continue;
    }
    ++storedMessageCount;
    if (message.sequence > newestSequence) {
      newestSequence = message.sequence;
      nextStoreSlot = (slot + 1) % kStoredMessageSlots;
    }
    if (timeKnown && (message.timestamp < kValidEpoch || now - message.timestamp > kHistoryWindowSeconds)) {
      continue;
    }

    // Keep the kMaxMessages highest sequence numbers, sorted ascending.
    if (count == kMaxMessages && message.sequence <= sequences[0]) {
      continue;
    }
    uint8_t position = count;
    if (count == kMaxMessages) {
      for (uint8_t index = 1; index < count; ++index) {
        sequences[index - 1] = sequences[index];
        slots[index - 1] = slots[index];
      }
      position = count - 1;
    } else {
      ++count;
    }
    while (position > 0 && sequences[position - 1] > message.sequence) {
      sequences[position] = sequences[position - 1];
      slots[position] = slots[position - 1];
      --position;
    }
    sequences[position] = message.sequence;
    slots[position] = slot;
  }
  nextStoreSequence = newestSequence + 1;

  for (uint8_t index = 0; index < count; ++index) {
    if (file.seek(static_cast<uint32_t>(slots[index]) * sizeof(StoredMessage)) &&
        file.read(reinterpret_cast<uint8_t *>(&message), sizeof(message)) == sizeof(message) &&
        isValidStoredMessage(message)) {
      rememberPacketId(message.packetId);
      displayMessage(message, false);
    }
  }
  file.close();
  Serial.printf("Message store: restored %u messages%s\n", count, timeKnown ? " from the last 24 h" : "");
}

void showTextMessage(uint32_t packetId, uint32_t sender, uint32_t to, uint32_t channel, uint32_t rxTime,
                     const uint8_t *payload, size_t payloadLength) {
  // The radio may resend queued messages after a reconnect.
  if (isRecentPacket(packetId)) {
    return;
  }

  StoredMessage message{};
  foldToAscii(payload, payloadLength, message.text, sizeof(message.text));
  if (message.text[0] == '\0') {
    return;
  }
  rememberPacketId(packetId);

  message.packetId = packetId;
  nodeDisplayName(sender, message.sender, sizeof(message.sender));
  channelDisplayName(channel, to, message.channel, sizeof(message.channel));
  const time_t now = time(nullptr);
  message.timestamp = rxTime >= kValidEpoch ? rxTime : (now >= kValidEpoch ? static_cast<uint32_t>(now) : 0);

  Serial.printf("[%s] %s: %s\n", message.channel, message.sender, message.text);
  storeMessage(message);
  displayMessage(message, true);
}

// User.long_name (field 2) from a User protobuf, folded to ASCII.
void parseUserLongName(const uint8_t *data, size_t length, char *destination, size_t destinationSize) {
  destination[0] = '\0';
  size_t offset = 0;
  ProtoField field{};
  while (offset < length && readProtoField(data, length, offset, field)) {
    if (field.number == 2 && field.wireType == 2) {
      foldToAscii(field.bytes, field.length, destination, destinationSize);
      return;
    }
  }
}

// DeviceMetrics.battery_level (field 1).
bool parseBatteryLevel(const uint8_t *data, size_t length, uint8_t &battery) {
  size_t offset = 0;
  ProtoField field{};
  while (offset < length && readProtoField(data, length, offset, field)) {
    if (field.number == 1 && field.wireType == 0) {
      battery = static_cast<uint8_t>(field.integer > 101 ? 101 : field.integer);
      return true;
    }
  }
  return false;
}

// User short_name (3), hw_model (5), role (7) of the local radio.
void parseLocalUser(const uint8_t *data, size_t length) {
  size_t offset = 0;
  ProtoField field{};
  radioInfo.hasUser = true;
  while (offset < length && readProtoField(data, length, offset, field)) {
    if (field.number == 3 && field.wireType == 2) {
      foldToAscii(field.bytes, field.length, radioInfo.shortName, sizeof(radioInfo.shortName));
    } else if (field.number == 5 && field.wireType == 0) {
      radioInfo.hwModel = static_cast<uint8_t>(field.integer);
    } else if (field.number == 7 && field.wireType == 0) {
      radioInfo.role = static_cast<uint8_t>(field.integer);
    }
  }
}

// DeviceMetrics of the local radio.
void parseLocalMetrics(const uint8_t *data, size_t length) {
  size_t offset = 0;
  ProtoField field{};
  while (offset < length && readProtoField(data, length, offset, field)) {
    if (field.number == 1 && field.wireType == 0) {
      radioInfo.hasBattery = true;
      radioInfo.battery = static_cast<uint8_t>(field.integer > 101 ? 101 : field.integer);
    } else if (field.number == 2 && field.wireType == 5) {
      radioInfo.hasVoltage = true;
      radioInfo.voltage = fixed32ToFloat(field.fixed32);
    } else if (field.number == 3 && field.wireType == 5) {
      radioInfo.hasChannelUtil = true;
      radioInfo.channelUtil = fixed32ToFloat(field.fixed32);
    } else if (field.number == 4 && field.wireType == 5) {
      radioInfo.hasAirUtilTx = true;
      radioInfo.airUtilTx = fixed32ToFloat(field.fixed32);
    } else if (field.number == 5 && field.wireType == 0) {
      radioInfo.hasUptime = true;
      radioInfo.uptimeSeconds = static_cast<uint32_t>(field.integer);
    }
  }
  radioInfo.metricsAt = millis();
}

// Position latitude_i (1), longitude_i (2), altitude (3) of the local radio.
void parseLocalPosition(const uint8_t *data, size_t length) {
  size_t offset = 0;
  ProtoField field{};
  bool hasLatitude = false;
  bool hasLongitude = false;
  while (offset < length && readProtoField(data, length, offset, field)) {
    if (field.number == 1 && field.wireType == 5) {
      radioInfo.latitudeI = static_cast<int32_t>(field.fixed32);
      hasLatitude = true;
    } else if (field.number == 2 && field.wireType == 5) {
      radioInfo.longitudeI = static_cast<int32_t>(field.fixed32);
      hasLongitude = true;
    } else if (field.number == 3 && field.wireType == 0) {
      radioInfo.altitude = static_cast<int32_t>(field.integer);
      radioInfo.hasAltitude = true;
    }
  }
  radioInfo.hasPosition = hasLatitude && hasLongitude && (radioInfo.latitudeI != 0 || radioInfo.longitudeI != 0);
}

// Config.lora (field 6): use_preset 1, modem_preset 2, region 7, hop_limit 8, tx_power 10.
void parseConfig(const uint8_t *data, size_t length) {
  size_t offset = 0;
  ProtoField field{};
  while (offset < length && readProtoField(data, length, offset, field)) {
    if (field.number != 6 || field.wireType != 2) {
      continue;
    }
    radioInfo.hasLora = true;
    radioInfo.usePreset = false;
    radioInfo.modemPreset = 0;
    radioInfo.region = 0;
    radioInfo.hopLimit = 0;
    radioInfo.txPower = 0;
    size_t loraOffset = 0;
    ProtoField loraField{};
    while (loraOffset < field.length && readProtoField(field.bytes, field.length, loraOffset, loraField)) {
      if (loraField.wireType != 0) {
        continue;
      }
      if (loraField.number == 1) {
        radioInfo.usePreset = loraField.integer != 0;
      } else if (loraField.number == 2) {
        radioInfo.modemPreset = static_cast<uint8_t>(loraField.integer);
      } else if (loraField.number == 7) {
        radioInfo.region = static_cast<uint8_t>(loraField.integer);
      } else if (loraField.number == 8) {
        radioInfo.hopLimit = static_cast<uint8_t>(loraField.integer);
      } else if (loraField.number == 10) {
        radioInfo.txPower = static_cast<int32_t>(loraField.integer);
      }
    }
  }
}

// DeviceMetadata.firmware_version (field 1).
void parseMetadata(const uint8_t *data, size_t length) {
  size_t offset = 0;
  ProtoField field{};
  while (offset < length && readProtoField(data, length, offset, field)) {
    if (field.number == 1 && field.wireType == 2) {
      foldToAscii(field.bytes, field.length, radioInfo.firmware, sizeof(radioInfo.firmware));
    }
  }
}

void parseNodeInfo(const uint8_t *data, size_t length) {
  size_t offset = 0;
  NodeEntry info{};
  info.hopsAway = kUnknownHops;
  ProtoField field{};

  while (offset < length && readProtoField(data, length, offset, field)) {
    if (field.number == 1 && field.wireType == 0) {
      info.number = static_cast<uint32_t>(field.integer);
    } else if (field.number == 2 && field.wireType == 2) {
      parseUserLongName(field.bytes, field.length, info.name, sizeof(info.name));
    } else if (field.number == 4 && field.wireType == 5) {
      info.snr = fixed32ToFloat(field.fixed32);
    } else if (field.number == 5 && field.wireType == 5) {
      info.lastHeard = field.fixed32;
    } else if (field.number == 6 && field.wireType == 2) {
      parseBatteryLevel(field.bytes, field.length, info.battery);
    } else if (field.number == 8 && field.wireType == 0) {
      info.viaMqtt = field.integer != 0;
    } else if (field.number == 9 && field.wireType == 0) {
      info.hopsAway = static_cast<uint8_t>(field.integer);
    }
  }

  if (info.number != 0 && info.number == localNodeNumber) {
    offset = 0;
    while (offset < length && readProtoField(data, length, offset, field)) {
      if (field.number == 2 && field.wireType == 2) {
        parseLocalUser(field.bytes, field.length);
      } else if (field.number == 3 && field.wireType == 2) {
        parseLocalPosition(field.bytes, field.length);
      } else if (field.number == 6 && field.wireType == 2) {
        parseLocalMetrics(field.bytes, field.length);
      }
    }
  }

  NodeEntry *entry = findOrAddNode(info.number);
  if (entry == nullptr) {
    return;
  }
  if (info.name[0] == '\0') {
    snprintf(info.name, sizeof(info.name), "%s", entry->name);
  }
  *entry = info;
}

// Telemetry.device_metrics (field 2) carries the sender's battery level; for the
// local radio it also refreshes the Info page.
void parseTelemetry(uint32_t sender, NodeEntry *node, const uint8_t *data, size_t length) {
  size_t offset = 0;
  ProtoField field{};
  while (offset < length && readProtoField(data, length, offset, field)) {
    if (field.number != 2 || field.wireType != 2) {
      continue;
    }
    if (sender != 0 && sender == localNodeNumber) {
      parseLocalMetrics(field.bytes, field.length);
    } else if (node != nullptr) {
      parseBatteryLevel(field.bytes, field.length, node->battery);
    }
  }
}

void parseChannel(const uint8_t *data, size_t length) {
  size_t offset = 0;
  uint32_t channelIndex = 0;
  uint32_t role = 0;
  char name[16] = {};
  ProtoField field{};

  while (offset < length && readProtoField(data, length, offset, field)) {
    if (field.number == 1 && field.wireType == 0) {
      channelIndex = static_cast<uint32_t>(field.integer);
    } else if (field.number == 3 && field.wireType == 0) {
      role = static_cast<uint32_t>(field.integer);
    } else if (field.number == 2 && field.wireType == 2) {
      size_t settingsOffset = 0;
      ProtoField settingsField{};
      while (settingsOffset < field.length &&
             readProtoField(field.bytes, field.length, settingsOffset, settingsField)) {
        if (settingsField.number == 3 && settingsField.wireType == 2) {
          foldToAscii(settingsField.bytes, settingsField.length, name, sizeof(name));
        }
      }
    }
  }

  if (channelIndex < kMaxChannels) {
    snprintf(channelNames[channelIndex], sizeof(channelNames[channelIndex]), "%s", name);
    channelEnabled[channelIndex] = role != 0;
  }
}

void parseMeshPacket(const uint8_t *data, size_t length) {
  size_t offset = 0;
  uint32_t sender = 0;
  uint32_t to = 0;
  uint32_t channel = 0;
  uint32_t rxTime = 0;
  uint32_t packetId = 0;
  uint32_t hopStart = 0;
  uint32_t hopLimit = 0;
  float rxSnr = 0;
  bool viaMqtt = false;
  const uint8_t *decodedData = nullptr;
  size_t decodedLength = 0;
  ProtoField field{};

  while (offset < length && readProtoField(data, length, offset, field)) {
    if (field.number == 1 && field.wireType == 5) {
      sender = field.fixed32;
    } else if (field.number == 2 && field.wireType == 5) {
      to = field.fixed32;
    } else if (field.number == 3 && field.wireType == 0) {
      channel = static_cast<uint32_t>(field.integer);
    } else if (field.number == 4 && field.wireType == 2) {
      decodedData = field.bytes;
      decodedLength = field.length;
    } else if (field.number == 6 && field.wireType == 5) {
      packetId = field.fixed32;
    } else if (field.number == 7 && field.wireType == 5) {
      rxTime = field.fixed32;
    } else if (field.number == 8 && field.wireType == 5) {
      rxSnr = fixed32ToFloat(field.fixed32);
    } else if (field.number == 9 && field.wireType == 0) {
      hopLimit = static_cast<uint32_t>(field.integer);
    } else if (field.number == 14 && field.wireType == 0) {
      viaMqtt = field.integer != 0;
    } else if (field.number == 15 && field.wireType == 0) {
      hopStart = static_cast<uint32_t>(field.integer);
    }
  }

  ++packetCount;
  lastPacketAt = millis();

  NodeEntry *node = sender != localNodeNumber ? findOrAddNode(sender) : nullptr;
  if (node != nullptr) {
    const time_t now = time(nullptr);
    node->lastHeard = rxTime >= kValidEpoch ? rxTime : (now >= kValidEpoch ? static_cast<uint32_t>(now) : 0);
    node->viaMqtt = viaMqtt;
    if (hopStart > 0 && hopStart >= hopLimit) {
      node->hopsAway = static_cast<uint8_t>(hopStart - hopLimit);
    }
    if (node->hopsAway == 0 && rxSnr != 0) {
      node->snr = rxSnr;
    }
  }

  // Packets without a decoded payload are on channels this node has no key for.
  if (decodedData == nullptr) {
    return;
  }

  offset = 0;
  uint32_t portNumber = 0;
  const uint8_t *payload = nullptr;
  size_t payloadLength = 0;
  while (offset < decodedLength && readProtoField(decodedData, decodedLength, offset, field)) {
    if (field.number == 1 && field.wireType == 0) {
      portNumber = static_cast<uint32_t>(field.integer);
    } else if (field.number == 2 && field.wireType == 2) {
      payload = field.bytes;
      payloadLength = field.length;
    }
  }

  if (portNumber == kPortTextMessage && payload != nullptr) {
    showTextMessage(packetId, sender, to, channel, rxTime, payload, payloadLength);
  } else if (portNumber == kPortNodeInfo && payload != nullptr) {
    char nodeName[32];
    parseUserLongName(payload, payloadLength, nodeName, sizeof(nodeName));
    rememberNodeName(sender, nodeName);
  } else if (portNumber == kPortTelemetry && payload != nullptr) {
    parseTelemetry(sender, node, payload, payloadLength);
  }
}

void handleFromRadio(const uint8_t *data, size_t length) {
  size_t offset = 0;
  ProtoField field{};
  while (offset < length && readProtoField(data, length, offset, field)) {
    if (field.wireType == 2 && field.number == 2) {
      parseMeshPacket(field.bytes, field.length);
    } else if (field.wireType == 2 && field.number == 4) {
      parseNodeInfo(field.bytes, field.length);
    } else if (field.wireType == 2 && field.number == 10) {
      parseChannel(field.bytes, field.length);
    } else if (field.wireType == 2 && field.number == 5) {
      parseConfig(field.bytes, field.length);
    } else if (field.wireType == 2 && field.number == 13) {
      parseMetadata(field.bytes, field.length);
    } else if (field.wireType == 2 && field.number == 3) {
      size_t infoOffset = 0;
      ProtoField infoField{};
      while (infoOffset < field.length && readProtoField(field.bytes, field.length, infoOffset, infoField)) {
        if (infoField.number == 1 && infoField.wireType == 0) {
          localNodeNumber = static_cast<uint32_t>(infoField.integer);
        } else if (infoField.number == 8 && infoField.wireType == 0) {
          radioInfo.hasRebootCount = true;
          radioInfo.rebootCount = static_cast<uint32_t>(infoField.integer);
        }
      }
    } else if (field.number == 7 && field.wireType == 0) {
      Serial.printf("Node database loaded: %u nodes\n", nodeCount);
      setLinkState(LinkState::Ready);
    }
  }
}

void processApiByte(uint8_t byte) {
  if (apiExpectedLength == 0) {
    if (apiHeaderLength == 0) {
      if (byte == 0x94) {
        apiHeader[0] = byte;
        apiHeaderLength = 1;
      }
      return;
    }
    if (apiHeaderLength == 1 && byte != 0xC3) {
      apiHeaderLength = byte == 0x94 ? 1 : 0;
      apiHeader[0] = byte;
      return;
    }
    apiHeader[apiHeaderLength++] = byte;
    if (apiHeaderLength == sizeof(apiHeader)) {
      apiExpectedLength = (static_cast<uint16_t>(apiHeader[2]) << 8) | apiHeader[3];
      apiHeaderLength = 0;
      if (apiExpectedLength == 0 || apiExpectedLength > sizeof(apiFrame)) {
        apiExpectedLength = 0;
      } else {
        apiReceivedLength = 0;
      }
    }
    return;
  }

  apiFrame[apiReceivedLength++] = byte;
  if (apiReceivedLength == apiExpectedLength) {
    handleFromRadio(apiFrame, apiExpectedLength);
    apiExpectedLength = 0;
    apiReceivedLength = 0;
  }
}

bool loadRadioAddress() {
  preferences.begin("radio", false);  // read-only would log an error while nothing is saved yet
  const uint32_t stored = preferences.getUInt("ip", 0);
  preferences.end();
  if (stored == 0) {
    return false;
  }
  radioAddress = IPAddress(stored);
  return true;
}

