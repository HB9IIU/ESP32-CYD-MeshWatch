bool readProtoVarint(const uint8_t *data, size_t length, size_t &offset, uint64_t &value) {
  value = 0;
  for (uint8_t shift = 0; shift < 64; shift += 7) {
    if (offset >= length) {
      return false;
    }
    const uint8_t byte = data[offset++];
    value |= static_cast<uint64_t>(byte & 0x7F) << shift;
    if ((byte & 0x80) == 0) {
      return true;
    }
  }
  return false;
}

struct ProtoField {
  uint32_t number;
  uint8_t wireType;
  uint64_t integer;
  uint32_t fixed32;
  const uint8_t *bytes;
  size_t length;
};

bool readProtoField(const uint8_t *data, size_t length, size_t &offset, ProtoField &field) {
  uint64_t key = 0;
  if (!readProtoVarint(data, length, offset, key) || key == 0) {
    return false;
  }

  field.number = static_cast<uint32_t>(key >> 3);
  field.wireType = static_cast<uint8_t>(key & 0x07);
  field.integer = 0;
  field.fixed32 = 0;
  field.bytes = nullptr;
  field.length = 0;

  if (field.wireType == 0) {
    return readProtoVarint(data, length, offset, field.integer);
  }
  if (field.wireType == 1) {
    if (length - offset < 8) {
      return false;
    }
    offset += 8;
    return true;
  }
  if (field.wireType == 2) {
    uint64_t fieldLength = 0;
    if (!readProtoVarint(data, length, offset, fieldLength) || fieldLength > length - offset) {
      return false;
    }
    field.bytes = data + offset;
    field.length = static_cast<size_t>(fieldLength);
    offset += field.length;
    return true;
  }
  if (field.wireType == 5) {
    if (length - offset < 4) {
      return false;
    }
    field.fixed32 = static_cast<uint32_t>(data[offset]) |
                    (static_cast<uint32_t>(data[offset + 1]) << 8) |
                    (static_cast<uint32_t>(data[offset + 2]) << 16) |
                    (static_cast<uint32_t>(data[offset + 3]) << 24);
    offset += 4;
    return true;
  }
  return false;
}

// Maps a Unicode code point to something the built-in ASCII fonts can draw.
// Returns ' ' for whitespace and 0 for characters that should be dropped (emoji etc.).
char foldCodePoint(uint32_t codePoint) {
  static const char kLatin1Base[] = "AAAAAAACEEEEIIIIDNOOOOOxOUUUUYTsaaaaaaaceeeeiiiidnooooo/ouuuuyty";
  if (codePoint == '\t' || codePoint == '\n' || codePoint == '\r' || codePoint == 0xA0) {
    return ' ';
  }
  if (codePoint >= 0x20 && codePoint <= 0x7E) {
    return static_cast<char>(codePoint);
  }
  if (codePoint >= 0xC0 && codePoint <= 0xFF) {
    return kLatin1Base[codePoint - 0xC0];
  }
  switch (codePoint) {
    case 0x2018:
    case 0x2019:
      return '\'';
    case 0x201C:
    case 0x201D:
      return '"';
    case 0x2013:
    case 0x2014:
      return '-';
    default:
      return 0;
  }
}

// Decodes UTF-8 into drawable ASCII: accents are stripped, emoji dropped,
// and whitespace runs collapsed and trimmed.
void foldToAscii(const uint8_t *source, size_t length, char *destination, size_t destinationSize) {
  if (destination == nullptr || destinationSize == 0) {
    return;
  }

  size_t outIndex = 0;
  size_t index = 0;
  bool pendingSpace = false;
  while (source != nullptr && index < length && outIndex + 1 < destinationSize) {
    const uint8_t lead = source[index];
    uint32_t codePoint = 0;
    size_t sequenceLength = 1;
    if (lead < 0x80) {
      codePoint = lead;
    } else if ((lead & 0xE0) == 0xC0) {
      codePoint = lead & 0x1F;
      sequenceLength = 2;
    } else if ((lead & 0xF0) == 0xE0) {
      codePoint = lead & 0x0F;
      sequenceLength = 3;
    } else if ((lead & 0xF8) == 0xF0) {
      codePoint = lead & 0x07;
      sequenceLength = 4;
    } else {
      ++index;
      continue;
    }
    if (index + sequenceLength > length) {
      break;
    }

    bool valid = true;
    for (size_t extra = 1; extra < sequenceLength; ++extra) {
      const uint8_t continuation = source[index + extra];
      if ((continuation & 0xC0) != 0x80) {
        valid = false;
        break;
      }
      codePoint = (codePoint << 6) | (continuation & 0x3F);
    }
    index += valid ? sequenceLength : 1;
    if (!valid) {
      continue;
    }

    const char mapped = foldCodePoint(codePoint);
    if (mapped == ' ') {
      pendingSpace = outIndex > 0;
      continue;
    }
    if (mapped == 0) {
      continue;
    }
    if (pendingSpace) {
      if (outIndex + 2 >= destinationSize) {
        break;
      }
      destination[outIndex++] = ' ';
      pendingSpace = false;
    }
    destination[outIndex++] = mapped;
  }
  destination[outIndex] = '\0';
}

NodeEntry *findNode(uint32_t nodeNumber) {
  for (uint8_t index = 0; index < nodeCount; ++index) {
    if (nodes[index].number == nodeNumber) {
      return &nodes[index];
    }
  }
  return nullptr;
}

NodeEntry *findOrAddNode(uint32_t nodeNumber) {
  if (nodeNumber == 0) {
    return nullptr;
  }

  NodeEntry *entry = findNode(nodeNumber);
  if (entry == nullptr) {
    if (nodeCount < kMaxNodes) {
      entry = &nodes[nodeCount++];
    } else {
      entry = &nodes[nextNodeSlot];
      nextNodeSlot = (nextNodeSlot + 1) % kMaxNodes;
    }
    *entry = NodeEntry{};
    entry->number = nodeNumber;
    entry->hopsAway = kUnknownHops;
  }
  nodeTableDirty = true;
  return entry;
}

void rememberNodeName(uint32_t nodeNumber, const char *name) {
  NodeEntry *entry = findOrAddNode(nodeNumber);
  if (entry != nullptr && name != nullptr && name[0] != '\0') {
    snprintf(entry->name, sizeof(entry->name), "%s", name);
  }
}

float fixed32ToFloat(uint32_t bits) {
  float value = 0;
  memcpy(&value, &bits, sizeof(value));
  return value;
}

void nodeDisplayName(uint32_t nodeNumber, char *destination, size_t destinationSize) {
  const NodeEntry *entry = findNode(nodeNumber);
  if (entry != nullptr && entry->name[0] != '\0') {
    snprintf(destination, destinationSize, "%s", entry->name);
  } else {
    snprintf(destination, destinationSize, "!%08lx", static_cast<unsigned long>(nodeNumber));
  }
}

const char *enumName(const char *const *names, size_t count, uint32_t value) {
  return value < count && names[value][0] != '\0' ? names[value] : nullptr;
}

// LONG_FAST -> LongFast, as the Meshtastic apps display presets.
void presetDisplayName(uint8_t preset, char *destination, size_t destinationSize) {
  const char *name = enumName(kModemPresetNames, sizeof(kModemPresetNames) / sizeof(kModemPresetNames[0]), preset);
  if (name == nullptr) {
    snprintf(destination, destinationSize, "Preset %u", preset);
    return;
  }
  size_t outIndex = 0;
  bool upper = true;
  for (size_t index = 0; name[index] != '\0' && outIndex + 1 < destinationSize; ++index) {
    if (name[index] == '_') {
      upper = true;
      continue;
    }
    destination[outIndex++] = upper ? name[index] : static_cast<char>(tolower(name[index]));
    upper = false;
  }
  destination[outIndex] = '\0';
}

void channelDisplayName(uint32_t channel, uint32_t to, char *destination, size_t destinationSize) {
  if (to != kBroadcastAddress && to == localNodeNumber) {
    snprintf(destination, destinationSize, "DM");
  } else if (channel < kMaxChannels && channelNames[channel][0] != '\0') {
    snprintf(destination, destinationSize, "%s", channelNames[channel]);
  } else if (channel == 0 && radioInfo.hasLora && radioInfo.usePreset) {
    presetDisplayName(radioInfo.modemPreset, destination, destinationSize);
  } else if (channel == 0) {
    snprintf(destination, destinationSize, "Primary");
  } else {
    snprintf(destination, destinationSize, "Ch %lu", static_cast<unsigned long>(channel));
  }
}

void formatClock(time_t timestamp, char *destination, size_t destinationSize) {
  if (timestamp < kValidEpoch) {
    snprintf(destination, destinationSize, "--:--");
    return;
  }
  struct tm local {};
  localtime_r(&timestamp, &local);
  strftime(destination, destinationSize, "%H:%M", &local);
}

void formatAge(uint32_t elapsedMs, char *destination, size_t destinationSize) {
  const uint32_t seconds = elapsedMs / 1000;
  if (seconds < 60) {
    snprintf(destination, destinationSize, "%lus ago", static_cast<unsigned long>(seconds));
  } else if (seconds < 3600) {
    snprintf(destination, destinationSize, "%lum ago", static_cast<unsigned long>(seconds / 60));
  } else {
    snprintf(destination, destinationSize, "%luh ago", static_cast<unsigned long>(seconds / 3600));
  }
}

void refreshStatus() {
  if (footerLabel == nullptr || statusDot == nullptr) {
    return;
  }

  char text[48];
  uint32_t dotColor = kColorWarn;
  switch (linkState) {
    case LinkState::Setup:
      snprintf(text, sizeof(text), "WiFi setup");
      dotColor = kColorBad;
      break;
    case LinkState::Searching:
      snprintf(text, sizeof(text), "Searching...");
      break;
    case LinkState::Connecting:
      snprintf(text, sizeof(text), "Connecting...");
      break;
    case LinkState::NotFound:
      snprintf(text, sizeof(text), "No radio");
      dotColor = kColorBad;
      break;
    case LinkState::Loading:
      snprintf(text, sizeof(text), "Loading %u", nodeCount);
      break;
    case LinkState::Down:
      snprintf(text, sizeof(text), "Radio down");
      dotColor = kColorBad;
      break;
    case LinkState::Ready: {
      if (packetCount > 0) {
        formatAge(millis() - lastPacketAt, text, sizeof(text));
      } else {
        snprintf(text, sizeof(text), "Ready");
      }
      dotColor = kColorGood;
      break;
    }
  }
  lv_label_set_text(footerLabel, text);
  lv_obj_set_style_bg_color(statusDot, lv_color_hex(dotColor), LV_PART_MAIN);
  const uint8_t remoteNodes = nodeCount - (findNode(localNodeNumber) != nullptr ? 1 : 0);
  lv_label_set_text_fmt(nodesTabLabel, "Nodes %u", remoteNodes);
}

