// Rebuilds the Info page. Rows are always the same, unknown values show "-".
void refreshInfoTable() {
  char value[64];
  infoRow = 0;

  addInfoSection("RADIO");
  const NodeEntry *self = localNodeNumber != 0 ? findNode(localNodeNumber) : nullptr;
  if (self != nullptr && self->name[0] != '\0') {
    if (radioInfo.shortName[0] != '\0') {
      snprintf(value, sizeof(value), "%s (%s)", self->name, radioInfo.shortName);
    } else {
      snprintf(value, sizeof(value), "%s", self->name);
    }
  } else {
    value[0] = '\0';
  }
  addInfoValue("Name", value);
  if (localNodeNumber != 0) {
    snprintf(value, sizeof(value), "!%08lx", static_cast<unsigned long>(localNodeNumber));
  } else {
    value[0] = '\0';
  }
  addInfoValue("Node ID", value);
  addInfoValue("Address", hasRadioAddress ? radioAddress.toString().c_str() : nullptr);

  value[0] = '\0';
  if (radioInfo.hasUser) {
    const char *name = enumName(kHardwareModelNames, sizeof(kHardwareModelNames) / sizeof(kHardwareModelNames[0]),
                                radioInfo.hwModel);
    if (name != nullptr) {
      snprintf(value, sizeof(value), "%s", name);
    } else {
      snprintf(value, sizeof(value), "Model %u", radioInfo.hwModel);
    }
  }
  addInfoValue("Hardware", value);
  value[0] = '\0';
  if (radioInfo.hasUser) {
    const char *name = enumName(kRoleNames, sizeof(kRoleNames) / sizeof(kRoleNames[0]), radioInfo.role);
    if (name != nullptr) {
      snprintf(value, sizeof(value), "%s", name);
    } else {
      snprintf(value, sizeof(value), "Role %u", radioInfo.role);
    }
  }
  addInfoValue("Role", value);
  addInfoValue("Firmware", radioInfo.firmware);

  value[0] = '\0';
  if (radioInfo.hasBattery) {
    const int written = radioInfo.battery > 100 ? snprintf(value, sizeof(value), "Powered")
                                                : snprintf(value, sizeof(value), "%u%%", radioInfo.battery);
    if (radioInfo.hasVoltage && written > 0) {
      snprintf(value + written, sizeof(value) - written, " (%.2f V)", radioInfo.voltage);
    }
  }
  addInfoValue("Battery", value);
  value[0] = '\0';
  if (radioInfo.hasChannelUtil) {
    snprintf(value, sizeof(value), "%.1f%%", radioInfo.channelUtil);
  }
  addInfoValue("Channel use", value);
  value[0] = '\0';
  if (radioInfo.hasAirUtilTx) {
    snprintf(value, sizeof(value), "%.1f%%", radioInfo.airUtilTx);
  }
  addInfoValue("Airtime TX", value);
  value[0] = '\0';
  if (radioInfo.hasUptime) {
    formatDuration(radioInfo.uptimeSeconds + (millis() - radioInfo.metricsAt) / 1000, value, sizeof(value));
  }
  addInfoValue("Uptime", value);
  value[0] = '\0';
  if (radioInfo.metricsAt != 0) {
    formatAge(millis() - radioInfo.metricsAt, value, sizeof(value));
  }
  addInfoValue("Metrics from", value);
  value[0] = '\0';
  if (radioInfo.hasRebootCount) {
    snprintf(value, sizeof(value), "%lu", static_cast<unsigned long>(radioInfo.rebootCount));
  }
  addInfoValue("Reboots", value);

  value[0] = '\0';
  if (radioInfo.hasLora) {
    const char *name = enumName(kRegionNames, sizeof(kRegionNames) / sizeof(kRegionNames[0]), radioInfo.region);
    if (name != nullptr) {
      snprintf(value, sizeof(value), "%s", name);
    } else {
      snprintf(value, sizeof(value), "Region %u", radioInfo.region);
    }
  }
  addInfoValue("Region", value);
  value[0] = '\0';
  if (radioInfo.hasLora) {
    if (radioInfo.usePreset) {
      presetDisplayName(radioInfo.modemPreset, value, sizeof(value));
    } else {
      snprintf(value, sizeof(value), "Custom");
    }
  }
  addInfoValue("Preset", value);
  value[0] = '\0';
  if (radioInfo.hasLora) {
    snprintf(value, sizeof(value), "%u", radioInfo.hopLimit);
  }
  addInfoValue("Hop limit", value);
  value[0] = '\0';
  if (radioInfo.hasLora) {
    if (radioInfo.txPower == 0) {
      snprintf(value, sizeof(value), "Default");
    } else {
      snprintf(value, sizeof(value), "%ld dBm", static_cast<long>(radioInfo.txPower));
    }
  }
  addInfoValue("TX power", value);

  value[0] = '\0';
  size_t used = 0;
  for (uint8_t index = 0; index < kMaxChannels && used < sizeof(value); ++index) {
    if (!channelEnabled[index]) {
      continue;
    }
    char name[16];
    channelDisplayName(index, kBroadcastAddress, name, sizeof(name));
    const int written = snprintf(value + used, sizeof(value) - used, "%s%s", used == 0 ? "" : ", ", name);
    if (written > 0) {
      used += static_cast<size_t>(written);
    }
  }
  addInfoValue("Channels", value);
  value[0] = '\0';
  if (radioInfo.hasPosition) {
    snprintf(value, sizeof(value), "%.5f, %.5f", radioInfo.latitudeI / 1e7, radioInfo.longitudeI / 1e7);
  }
  addInfoValue("Position", value);
  value[0] = '\0';
  if (radioInfo.hasPosition && radioInfo.hasAltitude) {
    snprintf(value, sizeof(value), "%ld m", static_cast<long>(radioInfo.altitude));
  }
  addInfoValue("Altitude", value);

  addInfoSection("MESH");
  snprintf(value, sizeof(value), "%u", nodeCount - (self != nullptr ? 1 : 0));
  addInfoValue("Nodes", value);
  snprintf(value, sizeof(value), "%lu", static_cast<unsigned long>(packetCount));
  addInfoValue("Packets heard", value);
  value[0] = '\0';
  if (packetCount > 0) {
    formatAge(millis() - lastPacketAt, value, sizeof(value));
  }
  addInfoValue("Last packet", value);

  addInfoSection("MESHWATCH");
  addInfoValue("Version", MESHWATCH_VERSION);
  if (WiFi.status() == WL_CONNECTED) {
    addInfoValue("IP address", WiFi.localIP().toString().c_str());
    snprintf(value, sizeof(value), "%s (%d dBm)", WiFi.SSID().c_str(), WiFi.RSSI());
    addInfoValue("WiFi", value);
  } else {
    addInfoValue("IP address", nullptr);
    addInfoValue("WiFi", linkState == LinkState::Setup ? "Setup mode" : "Disconnected");
  }
  formatDuration(millis() / 1000, value, sizeof(value));
  addInfoValue("Uptime", value);
  snprintf(value, sizeof(value), "%lu KB", static_cast<unsigned long>(ESP.getFreeHeap() / 1024));
  addInfoValue("Free memory", value);
  snprintf(value, sizeof(value), "%u of %u", storedMessageCount, kStoredMessageSlots);
  addInfoValue("Stored msgs", value);

  lv_table_set_row_cnt(infoTable, infoRow);
}

