void formatDuration(uint32_t seconds, char *destination, size_t destinationSize) {
  const unsigned long days = seconds / 86400;
  const unsigned long hours = (seconds % 86400) / 3600;
  const unsigned long minutes = (seconds % 3600) / 60;
  if (days > 0) {
    snprintf(destination, destinationSize, "%lud %luh", days, hours);
  } else if (hours > 0) {
    snprintf(destination, destinationSize, "%luh %lum", hours, minutes);
  } else {
    snprintf(destination, destinationSize, "%lum %lus", minutes, static_cast<unsigned long>(seconds % 60));
  }
}

