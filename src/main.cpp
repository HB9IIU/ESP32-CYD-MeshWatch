// ---- Screensaver: Swiss railway style clock with stop-to-go second hand ----

lv_obj_t *screensaverScreen = nullptr;
lv_obj_t *clockFace = nullptr;
lv_timer_t *clockFrameTimer = nullptr;
bool screensaverActive = false;
uint32_t screensaverWokenAt = 0;
float secondAngle = 0;  // degrees clockwise from 12
float minuteAngle = 0;
float hourAngle = 0;

void setBacklight(uint8_t level) {
  ledcWrite(TFT_BL, level);
}

// Point at `radius` from the clock centre in direction `angle` (degrees, clockwise from 12).
lv_point_t clockPoint(const lv_area_t &face, float radius, float angle) {
  const float radians = angle * static_cast<float>(M_PI) / 180.0f;
  const lv_coord_t centerX = (face.x1 + face.x2) / 2;
  const lv_coord_t centerY = (face.y1 + face.y2) / 2;
  return {static_cast<lv_coord_t>(lroundf(centerX + radius * sinf(radians))),
          static_cast<lv_coord_t>(lroundf(centerY - radius * cosf(radians)))};
}

// A bar along the radius from `inner` to `outer` (negative = behind the centre),
// tapering from `innerWidth` to `outerWidth`.
void drawRadialBar(lv_draw_ctx_t *drawCtx, const lv_area_t &face, float angle, float inner, float outer,
                   float innerWidth, float outerWidth, uint32_t color) {
  const float radians = angle * static_cast<float>(M_PI) / 180.0f;
  const float centerX = (face.x1 + face.x2) / 2.0f;
  const float centerY = (face.y1 + face.y2) / 2.0f;
  const float dirX = sinf(radians);
  const float dirY = -cosf(radians);
  const float sideX = cosf(radians);
  const float sideY = sinf(radians);
  const float corners[4][2] = {{inner, -innerWidth / 2}, {outer, -outerWidth / 2}, {outer, outerWidth / 2},
                               {inner, innerWidth / 2}};
  lv_point_t points[4];
  for (uint8_t index = 0; index < 4; ++index) {
    points[index].x = static_cast<lv_coord_t>(
        lroundf(centerX + dirX * corners[index][0] + sideX * corners[index][1]));
    points[index].y = static_cast<lv_coord_t>(
        lroundf(centerY + dirY * corners[index][0] + sideY * corners[index][1]));
  }
  lv_draw_rect_dsc_t dsc;
  lv_draw_rect_dsc_init(&dsc);
  dsc.bg_color = lv_color_hex(color);
  lv_draw_polygon(drawCtx, &dsc, points, 4);
}

void drawRing(lv_draw_ctx_t *drawCtx, lv_point_t center, lv_coord_t radius, lv_coord_t width, uint32_t color) {
  lv_draw_rect_dsc_t dsc;
  lv_draw_rect_dsc_init(&dsc);
  dsc.bg_opa = LV_OPA_TRANSP;
  dsc.border_color = lv_color_hex(color);
  dsc.border_width = width;
  dsc.radius = LV_RADIUS_CIRCLE;
  const lv_area_t area = {static_cast<lv_coord_t>(center.x - radius), static_cast<lv_coord_t>(center.y - radius),
                          static_cast<lv_coord_t>(center.x + radius), static_cast<lv_coord_t>(center.y + radius)};
  lv_draw_rect(drawCtx, &dsc, &area);
}

void drawDisc(lv_draw_ctx_t *drawCtx, lv_point_t center, lv_coord_t radius, uint32_t color) {
  lv_draw_rect_dsc_t dsc;
  lv_draw_rect_dsc_init(&dsc);
  dsc.bg_color = lv_color_hex(color);
  dsc.radius = LV_RADIUS_CIRCLE;
  const lv_area_t area = {static_cast<lv_coord_t>(center.x - radius), static_cast<lv_coord_t>(center.y - radius),
                          static_cast<lv_coord_t>(center.x + radius), static_cast<lv_coord_t>(center.y + radius)};
  lv_draw_rect(drawCtx, &dsc, &area);
}

// Dark face in the MeshWatch colours; proportions relative to the face radius.
void drawClockFace(lv_event_t *event) {
  lv_draw_ctx_t *drawCtx = lv_event_get_draw_ctx(event);
  lv_area_t face;
  lv_obj_get_coords(clockFace, &face);
  const float r = kClockRadius;

  lv_draw_rect_dsc_t faceDsc;
  lv_draw_rect_dsc_init(&faceDsc);
  faceDsc.bg_color = lv_color_hex(kClockFace);
  faceDsc.radius = LV_RADIUS_CIRCLE;
  faceDsc.border_color = lv_color_hex(kClockRim);
  faceDsc.border_width = 2;
  lv_draw_rect(drawCtx, &faceDsc, &face);

  for (uint8_t mark = 0; mark < 60; ++mark) {
    if (mark % 5 == 0) {
      drawRadialBar(drawCtx, face, mark * 6.0f, r * 0.70f, r * 0.95f, r * 0.075f, r * 0.075f, kClockInk);
    } else {
      drawDisc(drawCtx, clockPoint(face, r * 0.915f, mark * 6.0f), static_cast<lv_coord_t>(r * 0.022f) + 1,
               kClockInk);
    }
  }

  if (unreadCount > 0) {
    char text[24];
    snprintf(text, sizeof(text), "%u new message%s", unreadCount, unreadCount == 1 ? "" : "s");
    lv_draw_label_dsc_t labelDsc;
    lv_draw_label_dsc_init(&labelDsc);
    labelDsc.font = &lv_font_montserrat_14;
    labelDsc.color = lv_color_hex(kClockSecond);
    labelDsc.align = LV_TEXT_ALIGN_CENTER;
    const lv_coord_t textY = (face.y1 + face.y2) / 2 + static_cast<lv_coord_t>(r * 0.36f);
    const lv_area_t textArea = {face.x1, static_cast<lv_coord_t>(textY - 8), face.x2,
                                static_cast<lv_coord_t>(textY + 10)};
    lv_draw_label(drawCtx, &labelDsc, &textArea, text, nullptr);
  }

  drawRadialBar(drawCtx, face, hourAngle, -r * 0.20f, r * 0.64f, r * 0.115f, r * 0.095f, kClockInk);
  drawRadialBar(drawCtx, face, minuteAngle, -r * 0.20f, r * 0.92f, r * 0.090f, r * 0.068f, kClockInk);
  drawRadialBar(drawCtx, face, secondAngle, -r * 0.30f, r * 0.53f, r * 0.024f, r * 0.024f, kClockSecond);
  drawRing(drawCtx, clockPoint(face, r * 0.62f, secondAngle), static_cast<lv_coord_t>(r * 0.09f),
           static_cast<lv_coord_t>(r * 0.03f), kClockSecond);
  drawDisc(drawCtx, clockPoint(face, 0, 0), static_cast<lv_coord_t>(r * 0.04f), kClockSecond);
}

// Screen area covered by the second hand at `angle`, including tail and disc.
lv_area_t secondHandArea(const lv_area_t &face, float angle) {
  const float r = kClockRadius;
  const lv_point_t tail = clockPoint(face, -r * 0.30f, angle);
  const lv_point_t disc = clockPoint(face, r * 0.62f, angle);
  const lv_coord_t margin = static_cast<lv_coord_t>(r * 0.10f) + 3;
  return {static_cast<lv_coord_t>(min(tail.x, disc.x) - margin), static_cast<lv_coord_t>(min(tail.y, disc.y) - margin),
          static_cast<lv_coord_t>(max(tail.x, disc.x) + margin), static_cast<lv_coord_t>(max(tail.y, disc.y) + margin)};
}

// Stop-to-go: the second hand sweeps the dial in 58.5 s, waits at 12, and the minute
// hand jumps when the new minute starts.
void animateClock(lv_timer_t *timer) {
  (void)timer;
  timeval now{};
  gettimeofday(&now, nullptr);
  float newSecond = 0;
  float newMinute = 0;
  float newHour = 0;
  if (now.tv_sec >= kValidEpoch) {
    struct tm local {};
    const time_t seconds = now.tv_sec;
    localtime_r(&seconds, &local);
    const float elapsed = local.tm_sec + now.tv_usec / 1e6f;
    newSecond = elapsed >= 58.5f ? 0.0f : elapsed / 58.5f * 360.0f;
    newMinute = local.tm_min * 6.0f;
    newHour = (local.tm_hour % 12) * 30.0f + local.tm_min * 0.5f;
  }

  lv_area_t face;
  lv_obj_get_coords(clockFace, &face);
  if (newMinute != minuteAngle || newHour != hourAngle) {
    minuteAngle = newMinute;
    hourAngle = newHour;
    secondAngle = newSecond;
    lv_obj_invalidate(clockFace);
  } else if (newSecond != secondAngle) {
    const lv_area_t before = secondHandArea(face, secondAngle);
    const lv_area_t after = secondHandArea(face, newSecond);
    const lv_area_t dirty = {min(before.x1, after.x1), min(before.y1, after.y1), max(before.x2, after.x2),
                             max(before.y2, after.y2)};
    secondAngle = newSecond;
    lv_obj_invalidate_area(clockFace, &dirty);
  }

  if (screensaverWokenAt != 0 && millis() - screensaverWokenAt >= kScreensaverWakeMs) {
    screensaverWokenAt = 0;
    setBacklight(kBacklightDimmed);
  }
}

// The unread count is printed on the dial, so redraw the face when it changes.
void refreshScreensaverBadge() {
  if (clockFace != nullptr) {
    lv_obj_invalidate(clockFace);
  }
}

void onScreensaverMessage(bool unread) {
  if (unread && screensaverActive) {
    setBacklight(kBacklightFull);
    screensaverWokenAt = millis();
  }
}

void startScreensaver() {
  screensaverActive = true;
  screensaverWokenAt = 0;
  refreshScreensaverBadge();
  animateClock(nullptr);
  lv_obj_invalidate(clockFace);
  lv_scr_load(screensaverScreen);
  lv_timer_resume(clockFrameTimer);
  setBacklight(kBacklightDimmed);
}

void stopScreensaver(lv_event_t *event) {
  (void)event;
  if (!screensaverActive) {
    return;
  }
  screensaverActive = false;
  lv_timer_pause(clockFrameTimer);
  setBacklight(kBacklightFull);
  lv_scr_load(monitorScreen);
  if (unreadCount > 0) {
    showPage(Page::Messages);
  }
}

void createScreensaverScreen() {
  screensaverScreen = lv_obj_create(nullptr);
  lv_obj_set_style_bg_color(screensaverScreen, lv_color_black(), LV_PART_MAIN);
  lv_obj_clear_flag(screensaverScreen, LV_OBJ_FLAG_SCROLLABLE);
  lv_obj_add_event_cb(screensaverScreen, stopScreensaver, LV_EVENT_CLICKED, nullptr);

  clockFace = lv_obj_create(screensaverScreen);
  lv_obj_remove_style_all(clockFace);
  lv_obj_set_size(clockFace, kClockRadius * 2 + 1, kClockRadius * 2 + 1);
  lv_obj_center(clockFace);
  lv_obj_clear_flag(clockFace, LV_OBJ_FLAG_CLICKABLE | LV_OBJ_FLAG_SCROLLABLE);
  lv_obj_add_event_cb(clockFace, drawClockFace, LV_EVENT_DRAW_MAIN, nullptr);

  clockFrameTimer = lv_timer_create(animateClock, kClockFrameMs, nullptr);
  lv_timer_pause(clockFrameTimer);
}

void updateClock(lv_timer_t *timer) {
  (void)timer;
  if (!screensaverActive && lv_scr_act() == monitorScreen && linkState != LinkState::Setup &&
      lv_disp_get_inactive_time(nullptr) >= kScreensaverIdleMs) {
    startScreensaver();
  }
  char clock[8];
  formatClock(time(nullptr), clock, sizeof(clock));
  lv_label_set_text(clockLabel, clock);
  refreshStatus();
  if (activePage == Page::Nodes &&
      (nodeTableDirty || millis() - lastNodeTableRefresh >= kNodeTableRefreshMs)) {
    refreshNodeTable();
  } else if (activePage == Page::Info) {
    refreshInfoTable();
  }
}

