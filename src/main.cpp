void setup() {
  Serial.begin(115200);
  Serial.printf("MeshWatch %s\n", MESHWATCH_VERSION);

  ledcAttach(TFT_BL, 5000, 8);
  ledcWrite(TFT_BL, kBacklightFull);
  pinMode(touchCs, OUTPUT);
  digitalWrite(touchCs, HIGH);
  pinMode(touchIrq, INPUT);

  tft.begin();
  tft.setRotation(displayRotation);
  touchSpi.begin(touchClk, touchMiso, touchMosi, touchCs);

  lv_init();
  lv_disp_draw_buf_init(&drawBuffer, buffer1, buffer2, screenWidth * drawBufferLines);

  static lv_disp_drv_t displayDriver;
  lv_disp_drv_init(&displayDriver);
  displayDriver.hor_res = screenWidth;
  displayDriver.ver_res = screenHeight;
  displayDriver.flush_cb = flushDisplay;
  displayDriver.draw_buf = &drawBuffer;
  lv_disp_drv_register(&displayDriver);

  static lv_indev_drv_t touchDriver;
  lv_indev_drv_init(&touchDriver);
  touchDriver.type = LV_INDEV_TYPE_POINTER;
  touchDriver.read_cb = readTouchForLvgl;
  lv_indev_drv_register(&touchDriver);

  createMonitorScreen();
  createScreensaverScreen();
  createSplashScreen();

  hasRadioAddress = !kForceRadioDiscovery && loadRadioAddress();
  initMessageStore();
  if (!connectToStoredWifi()) {
    restoreMessages();
    startCaptivePortal();
  } else {
    // The 24 h history window needs the real time, which NTP delivers shortly after WiFi.
    setSplashStatus("Syncing time...");
    struct tm now {};
    getLocalTime(&now, kTimeSyncWaitMs);
    setSplashStatus("Loading message history...");
    restoreMessages();
    hasRadioConnectAttempted = true;
    lastRadioConnectAttempt = millis();
    startRadioApi();
  }
  finishSplash();
}

void loop() {
  if (WiFi.status() != WL_CONNECTED) {
    dnsServer.processNextRequest();
    webServer.handleClient();
  } else {
    serviceRadioApi();
  }

  lv_timer_handler();
  delay(5);
}
