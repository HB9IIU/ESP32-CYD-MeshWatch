bool saveWifiCredentials(const String &ssid, const String &password) {
  preferences.begin("wifi_cfg", false);
  const bool ok = preferences.putString("ssid", ssid) && preferences.putString("password", password);
  preferences.end();
  return ok;
}

bool loadWifiCredentials(String &ssid, String &password) {
  preferences.begin("wifi_cfg", false);  // read-only would log an error while nothing is saved yet
  const bool hasSsid = preferences.isKey("ssid");
  const bool hasPassword = preferences.isKey("password");
  if (hasSsid && hasPassword) {
    ssid = preferences.getString("ssid");
    password = preferences.getString("password");
    preferences.end();
    return !ssid.isEmpty() && !password.isEmpty();
  }
  preferences.end();
  return false;
}

bool connectToStoredWifi() {
  String ssid;
  String password;
  if (!loadWifiCredentials(ssid, password)) {
    return false;
  }

  Serial.printf("Connecting to saved WiFi SSID: %s\n", ssid.c_str());
  char splashText[64];
  snprintf(splashText, sizeof(splashText), "Connecting to WiFi %s...", ssid.c_str());
  setSplashStatus(splashText);
  WiFi.mode(WIFI_STA);
  WiFi.begin(ssid.c_str(), password.c_str());

  uint32_t start = millis();
  while (WiFi.status() != WL_CONNECTED && millis() - start < 15000) {
    delay(250);
    Serial.print('.');
  }

  if (WiFi.status() == WL_CONNECTED) {
    Serial.println();
    Serial.print("WiFi connected. IP: ");
    Serial.println(WiFi.localIP());
    configTzTime(kTimeZone, kNtpServer);
    return true;
  }

  WiFi.disconnect(true);
  return false;
}

